export function getCaseStudy(slug) {
  return caseStudies.find((study) => study.slug === slug);
}

export function getRelatedCaseStudies(currentStudy) {
  return caseStudies.filter((study) => study.slug !== currentStudy.slug).slice(0, 2);
}
